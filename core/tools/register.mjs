// Scans videos/*/ and writes src/registry.ts so Remotion knows every video. Run after adding a video.
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const vdir = path.join(root, "videos");
const names = fs.readdirSync(vdir).filter((n) => fs.existsSync(path.join(vdir, n, "video.json")) && fs.existsSync(path.join(vdir, n, "scenes.json")) && fs.existsSync(path.join(vdir, n, "timing.json")));
let out = "// GENERATED by tools/register.mjs - do not edit\nimport type { Timing } from \"./engine/timing\";\nimport type { SceneSpec, VideoCfg } from \"./engine/Video\";\n";
names.forEach((n, i) => {
  out += `import cfg${i} from "../videos/${n}/video.json";\nimport scenes${i} from "../videos/${n}/scenes.json";\nimport timing${i} from "../videos/${n}/timing.json";\n`;
  if (fs.existsSync(path.join(vdir, n, "thumb.json"))) out += `import thumb${i} from "../videos/${n}/thumb.json";\n`;
});
out += "export const REGISTRY: { cfg: VideoCfg; scenes: SceneSpec[]; timing: Timing; thumb?: any }[] = [\n";
names.forEach((n, i) => {
  const hasThumb = fs.existsSync(path.join(vdir, n, "thumb.json"));
  out += `  { cfg: cfg${i} as unknown as VideoCfg, scenes: scenes${i} as unknown as SceneSpec[], timing: timing${i} as Timing${hasThumb ? `, thumb: thumb${i}` : ""} },\n`;
});
out += "];\n";
fs.writeFileSync(path.join(root, "src", "registry.ts"), out);
console.log("registered:", names.join(", ") || "(none)");
