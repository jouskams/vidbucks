# -*- coding: utf-8 -*-
"""Export a map region for the GeoMap engine from Natural Earth (public domain).

  python tools/geo_export.py --name europe --lon -26 62 --lat 30 73

Downloads (once) into data/naturalearth/: 1:50m grey + colour shaded relief, 1:10m countries, 1:10m rivers.
Writes public/geo/<name>_relief.jpg, public/geo/<name>_color.jpg and src/geo/<name>.ts (simplified polygons + rivers).
GeoMap currently imports src/geo/europe.ts, so export under --name europe to replace the map."""
import argparse, json, os, urllib.request, zipfile
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "naturalearth")
SRC = {
    "GRAY_50M_SR_OB.zip": "https://naciscdn.org/naturalearth/50m/raster/GRAY_50M_SR_OB.zip",
    "NE1_50M_SR_W.zip": "https://naciscdn.org/naturalearth/50m/raster/NE1_50M_SR_W.zip",
    "countries10.geojson": "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson",
    "rivers10.geojson": "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_rivers_lake_centerlines.geojson",
}
ap = argparse.ArgumentParser()
ap.add_argument("--name", default="europe")
ap.add_argument("--lon", nargs=2, type=float, default=[-26, 62])
ap.add_argument("--lat", nargs=2, type=float, default=[30, 73])
ap.add_argument("--rivers", default="Rhine,Rhein,Waal,Lek,IJssel,Maas,Meuse,Schelde,Escaut,Volga,Dnieper,Don,Danube,Donau,Vistula,Wisla,Elbe,Oder,Odra,Seine,Loire,Thames,Neva,Ural")
a = ap.parse_args()
os.makedirs(DATA, exist_ok=True)
for fn, url in SRC.items():
    p = os.path.join(DATA, fn)
    if not os.path.exists(p):
        print("download", fn, flush=True); urllib.request.urlretrieve(url, p)
    if fn.endswith(".zip"):
        with zipfile.ZipFile(p) as z:
            for m in z.namelist():
                if m.lower().endswith(".tif") and not os.path.exists(os.path.join(DATA, os.path.basename(m))):
                    with z.open(m) as src, open(os.path.join(DATA, os.path.basename(m)), "wb") as dst: dst.write(src.read())

LON0, LON1 = a.lon; LAT0, LAT1 = a.lat
Image.MAX_IMAGE_PIXELS = None
for tif, out, mode in (("GRAY_50M_SR_OB.tif", f"{a.name}_relief.jpg", "L"), ("NE1_50M_SR_W.tif", f"{a.name}_color.jpg", "RGB")):
    im = Image.open(os.path.join(DATA, tif)); ppd = im.size[0] / 360
    crop = im.crop((int((LON0 + 180) * ppd), int((90 - LAT1) * ppd), int((LON1 + 180) * ppd), int((90 - LAT0) * ppd))).convert(mode)
    crop.save(os.path.join(ROOT, "public", "geo", out), quality=90); print(out, crop.size)

def simplify(pts, tol):
    out = [pts[0]]
    for p in pts[1:]:
        if abs(p[0] - out[-1][0]) + abs(p[1] - out[-1][1]) >= tol: out.append(p)
    if out[-1] != pts[-1]: out.append(pts[-1])
    return [[round(x, 3), round(y, 3)] for x, y in out]
def inbox(r):
    xs = [p[0] for p in r]; ys = [p[1] for p in r]
    return max(xs) >= LON0 and min(xs) <= LON1 and max(ys) >= LAT0 and min(ys) <= LAT1
SMALL = {"NLD", "BEL", "LUX", "CHE", "SVN", "MNE", "MKD", "ALB", "KOS", "AND", "MCO", "LIE", "SMR", "MLT", "CYP"}
countries = []
for f in json.load(open(os.path.join(DATA, "countries10.geojson")))["features"]:
    p = f["properties"]; g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    rings = []
    for poly in polys:
        r = poly[0]
        if len(r) < 4 or not inbox(r): continue
        s = simplify(r, 0.006 if p.get("ADM0_A3") in SMALL else 0.035)
        if len(s) >= 4: rings.append(s)
    if rings: countries.append({"iso": p.get("ADM0_A3"), "name": p.get("NAME"), "rings": rings, "lab": [p.get("LABEL_X"), p.get("LABEL_Y")]})
alias = {"Rhein": "Rhine", "Waal": "Rhine", "Lek": "Rhine", "IJssel": "Rhine", "Maas": "Meuse", "Escaut": "Scheldt", "Schelde": "Scheldt", "Donau": "Danube", "Wisla": "Vistula", "Odra": "Oder"}
want = set(a.rivers.split(","))
rivers = []
for f in json.load(open(os.path.join(DATA, "rivers10.geojson")))["features"]:
    n = f["properties"].get("name") or ""
    if n not in want: continue
    g = f["geometry"]; lines = g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]
    for ln in lines:
        if inbox(ln): rivers.append({"name": alias.get(n, n), "pts": simplify(ln, 0.012)})
data = {"bounds": [LON0, LAT0, LON1, LAT1], "countries": countries, "rivers": rivers}
s = json.dumps(data, separators=(",", ":"))
var = a.name.upper()
open(os.path.join(ROOT, "src", "geo", f"{a.name}.ts"), "w").write(f"// Natural Earth (public domain) 1:10m countries + rivers, simplified. Generated by tools/geo_export.py\nexport const {var}: {{bounds:number[];countries:{{iso:string;name:string;rings:number[][][];lab:number[]}}[];rivers:{{name:string;pts:number[][]}}[]}} = {s};\n")
print(len(countries), "countries", len(rivers), "river lines", round(len(s) / 1024), "KB", sorted({r["name"] for r in rivers}))
